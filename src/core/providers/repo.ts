// Repository-level sources: task runners (Makefile, justfile, Taskfile), READMEs, and git features a fresh clone
// may be missing (submodules, LFS objects).
import type { Ctx } from '../context.js';
import { ev, withRole } from '../context.js';
import { dirOf, joinRel } from '../fs.js';
import { parseJustfile, parseMakefile, parseMarkdownBlocks } from '../parse/textformats.js';
import { readDoc, asRecord, asStringArray, asString } from '../parse/structured.js';
import { classifyLine } from '../commands.js';
import { redactCommand } from '../parse/envfile.js';
import { addMentions } from './ci.js';
import { taskPurpose } from './php.js';

export const MAKEFILES = ['Makefile', 'makefile', 'GNUmakefile'];
export const JUSTFILES = ['justfile', 'Justfile', '.justfile'];
export const TASKFILES = ['Taskfile.yml', 'Taskfile.yaml', 'taskfile.yml', 'taskfile.yaml'];

export function collectTaskRunners(ctx: Ctx): void {
  const dirs = new Set(['.', ...ctx.projects.map((p) => p.root)]);
  for (const dir of [...dirs].sort()) {
    const project = ctx.projectAt(dir)?.id ?? 'root';
    for (const name of [...MAKEFILES, ...JUSTFILES, ...TASKFILES]) {
      const file = joinRel(dir, name);
      if (!ctx.files.isFile(file)) continue;
      const text = ctx.files.readText(file);
      if (text === null) continue;
      if (TASKFILES.includes(name)) {
        const doc = readDoc(ctx.files, file, 'yaml');
        if (!doc) continue;
        for (const [task, raw] of Object.entries(asRecord(asRecord(doc.value).tasks))) {
          const t = asRecord(raw);
          const cmds = (Array.isArray(t.cmds) ? t.cmds : []).map((c) => asString(c) ?? asString(asRecord(c).cmd) ?? (asRecord(c).task ? `task ${asString(asRecord(c).task)}` : '')).filter(Boolean) as string[];
          const line = doc.line(['tasks', task]) ?? 1;
          const purpose = taskPurpose(task);
          ctx.tasks.push({ runner: 'task', name: task, project, file, line, commands: cmds.map(redactCommand), purpose });
          if (purpose !== 'other') cmds.forEach((c) => addMentions(ctx, c, file, line, dir, 'task-runner', 'dev'));
        }
        continue;
      }
      const isMake = MAKEFILES.includes(name);
      for (const t of isMake ? parseMakefile(text) : parseJustfile(text)) {
        const purpose = taskPurpose(t.name);
        ctx.tasks.push({ runner: isMake ? 'make' : 'just', name: t.name, project, file, line: t.line, commands: t.commands.map(redactCommand), purpose });
        if (purpose !== 'other') t.commands.forEach((c, i) => addMentions(ctx, c, file, t.line + 1 + i, dir, 'task-runner', 'dev'));
      }
      ctx.toolClaims.push({ tool: isMake ? 'make' : 'just', project, optional: true, why: `${file} defines tasks you can run instead of the individual commands.`, source: 'task-runner', evidence: ev(file, undefined, 'task-runner', `${name} present`) });
    }
  }
}

const SHELL_LANGS = new Set(['', 'sh', 'bash', 'shell', 'console', 'zsh', 'terminal', 'shell-session', 'shellsession', 'powershell', 'ps1', 'pwsh', 'ps', 'cmd', 'bat', 'fish']);
const SKIP_HEADING = /(deploy|production|prod\b|release|publish|kubernetes|k8s|helm|heroku|vercel|netlify|fly\.io|railway|render\.com|upgrad|migrat(e|ing) from|license|sponsor|uninstall)/i;

/** Developer docs read for commands: READMEs, CONTRIBUTING and development guides (not generated SETUP.md files). */
export function docFiles(ctx: Ctx): string[] {
  const out: string[] = [];
  const dirs = new Set(['.', ...ctx.projects.map((p) => p.root)]);
  for (const dir of [...dirs].sort()) {
    for (const e of ctx.files.list(dir)) {
      if (!e.isFile) continue;
      if (/^readme(\.md|\.markdown)?$/i.test(e.name) || (dir === '.' && /^(contributing|development|developing|hacking|install|setup|local[-_]?development)\.mdx?$/i.test(e.name))) out.push(joinRel(dir, e.name));
    }
  }
  for (const f of ctx.entries.files) {
    if (out.includes(f)) continue;
    if (/^\.github\/contributing\.md$/i.test(f)) out.push(f);
    else if (/^(docs?|documentation|dev)\/([^/]+\/)?[^/]*(develop|contribut|setup|install|getting[-_ ]?started|local|quick[-_ ]?start|running)[^/]*\.mdx?$/i.test(f)) out.push(f);
  }
  return out.filter((f) => {
    if (!/setup\.md$/i.test(f)) return true;
    const head = ctx.files.readText(f)?.slice(0, 400) ?? '';
    return !/Generated by seefast/.test(head);
  });
}

export function collectReadmes(ctx: Ctx): void {
  for (const file of docFiles(ctx)) {
    const dir = dirOf(file).split('/').some((s) => /^(docs?|documentation|dev|\.github)$/i.test(s)) ? '.' : dirOf(file);
    const text = ctx.files.readText(file);
    if (text === null) continue;
    for (const block of parseMarkdownBlocks(text)) {
      if (!SHELL_LANGS.has(block.lang)) continue;
      if (block.headings.some((h) => SKIP_HEADING.test(h))) continue;
      const prompted = block.lines.some((l) => /^\s*[$>%]\s/.test(l));
      let cwd = dir;
      block.lines.forEach((raw, i) => {
        let l = raw;
        if (block.lang === 'console' || block.lang === 'shell-session' || prompted) {
          const m = /^\s*(?:[\w@.~:/-]*\s*)?[$>%]\s+(.*)$/.exec(l);
          if (!m) return; // output, not a command
          l = m[1];
        }
        l = l.trim();
        if (!l || l.startsWith('#') || l.startsWith('//')) return;
        for (const sig of classifyLine(l)) {
          if (sig.kind === 'cd') {
            // Follow `cd api` only into directories that exist here (`cd my-app` after `git clone` is the repo itself).
            const target = sig.key.slice(3);
            if (target && /^[\w./-]+$/.test(target) && !target.startsWith('/') && ctx.files.isDir(joinRel(cwd, target))) cwd = joinRel(cwd, target);
            continue;
          }
          if (sig.kind === 'other') {
            if (!/^(git|echo|open|export|set|source|\.|curl|wget|brew|apt|apt-get|sudo|winget|choco|scoop|nvm|fnm|volta|mise|asdf|code|mkdir|chmod|ls|cat)$/.test(sig.tool ?? '')) ctx.readmeIgnored++;
            continue;
          }
          ctx.mentions.push({ project: ctx.projectAt(cwd)?.id, sig, source: 'readme', scope: 'dev', headings: block.headings, evidence: ev(file, block.line + i, 'readme', redactCommand(l).slice(0, 160)) });
        }
      });
    }
  }
}

export function collectGit(ctx: Ctx): void {
  if (ctx.files.isFile('.gitmodules')) {
    const text = ctx.files.readText('.gitmodules') ?? '';
    const subs = [...text.matchAll(/^\s*path\s*=\s*(.+)$/gm)].map((m) => m[1].trim());
    const missing = subs.filter((s) => ctx.files.list(s).length === 0);
    ctx.addStep({
      local: 'submodules', project: ctx.projects[0]?.id ?? 'root', phase: 'prepare', order: 1,
      title: 'Fetch git submodules', cwd: '.', action: { type: 'exec', argv: ['git', 'submodule', 'update', '--init', '--recursive'] },
      network: true, thirdPartyCode: false, requires: ['tool:git'],
      confidence: 'high',
      why: `.gitmodules declares ${subs.length} submodule${subs.length === 1 ? '' : 's'} (${subs.join(', ')}), which a plain clone does not fetch.${missing.length ? ` ${missing.length} of them ${missing.length === 1 ? 'is' : 'are'} empty here.` : ''}`,
      evidence: [withRole(ev('.gitmodules', 1, 'manifest', `${subs.length} submodule(s)`), 'basis')],
      sig: 'submodule',
    });
    ctx.toolClaims.push({ tool: 'git', optional: false, why: 'Submodules are fetched with git.', source: 'manifest', evidence: ev('.gitmodules', 1, 'manifest', '.gitmodules present') });
  }
  if (ctx.files.isFile('.gitattributes')) {
    const text = ctx.files.readText('.gitattributes') ?? '';
    const lines = text.split('\n');
    const i = lines.findIndex((l) => /filter=lfs/.test(l));
    if (i >= 0) {
      ctx.toolClaims.push({ tool: 'git-lfs', optional: false, why: 'Some files are stored with Git LFS.', source: 'manifest', evidence: ev('.gitattributes', i + 1, 'manifest', lines[i].trim()) });
      ctx.addStep({
        local: 'lfs', project: ctx.projects[0]?.id ?? 'root', phase: 'prepare', order: 2,
        title: 'Download Git LFS files', cwd: '.', action: { type: 'exec', argv: ['git', 'lfs', 'pull'] },
        network: true, thirdPartyCode: false, requires: ['tool:git-lfs'], confidence: 'high',
        why: '.gitattributes stores files with Git LFS; without git-lfs a clone holds small pointer files instead of the real content.',
        evidence: [withRole(ev('.gitattributes', i + 1, 'manifest', lines[i].trim()), 'basis')],
      });
    }
  }
  void dirOf;
  void asStringArray;
}

/**
 * Generic fallback: a project with no install step from any provider gets the repo's own setup task
 * (`make setup`, `just bootstrap`, `task install`) as a low-confidence step, and its run task as a run target.
 */
export function genericTaskFallback(ctx: Ctx): void {
  for (const p of ctx.projects) {
    if (ctx.steps.some((s) => s.project === p.id && s.phase === 'install')) continue;
    const tasks = ctx.tasks.filter((t) => t.project === p.id && (t.runner === 'make' || t.runner === 'just' || t.runner === 'task'));
    const setup = tasks.find((t) => t.purpose === 'setup');
    const runT = tasks.find((t) => t.purpose === 'run');
    const argv = (t: (typeof tasks)[number]) => [t.runner, t.name];
    if (setup) {
      ctx.addStep({
        local: `task-${setup.name}`, project: p.id, phase: 'install', order: 10, title: `Run the repo's "${setup.name}" task (${setup.runner})`,
        cwd: p.root, action: { type: 'exec', argv: argv(setup) }, network: true, thirdPartyCode: true, requires: [`tool:${setup.runner}`],
        confidence: 'low',
        why: `No supported manifest says how to install this project, but ${setup.file} defines "${setup.name}", which by its name sets the project up. It runs: ${setup.commands.slice(0, 3).join('; ')}${setup.commands.length > 3 ? '; …' : ''}`,
        notes: ['Generic fallback: read the task before running it; this tool does not know what it does.'],
        evidence: [withRole(ev(setup.file, setup.line, 'task-runner', `${setup.name}: ${setup.commands[0] ?? ''}`.trim()), 'basis')],
        sig: `${setup.runner}:${setup.name}`,
      });
    }
    if (runT && !ctx.runs.some((r) => r.project === p.id && r.kind === 'dev')) {
      ctx.addRun({
        local: `task-${runT.name}`, project: p.id, name: runT.name, kind: 'dev', primary: true, title: `Run the repo's "${runT.name}" task (${runT.runner})`,
        cwd: p.root, action: { type: 'exec', argv: argv(runT) }, readiness: { type: 'stays-up', seconds: 20 }, confidence: 'low',
        why: `${runT.file} defines "${runT.name}": ${runT.commands.slice(0, 2).join('; ')}`,
        evidence: [withRole(ev(runT.file, runT.line, 'task-runner', `${runT.name}: ${runT.commands[0] ?? ''}`.trim()), 'basis')],
        sig: `${runT.runner}:${runT.name}`,
      });
    }
  }
}
