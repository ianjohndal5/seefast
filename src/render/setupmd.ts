// SETUP.md: the manual guide as a Markdown document, with commands for both shells. Only written on request.
import type { Plan, Step } from '../core/schema.js';
import { renderAction, renderCd } from './shell.js';
import { label, projectLabel, ref, requirementLine, serviceLine } from './text.js';

export function renderSetupMd(plan: Plan): string {
  const o: string[] = [];
  const p = (s = '') => o.push(s);
  p(`# Setting up ${plan.meta.rootName}`);
  p();
  p(`> Generated by ${plan.tool.name} ${plan.tool.version} from the repository's own files (plan \`${plan.digest.slice(0, 19)}…\`). Every item links to the file it comes from. Items marked *likely* or *guess* are inferred, not stated by the repo; check them.`);
  p();
  if (!plan.projects.length) {
    p('No project manifest was found in this folder.');
    return o.join('\n') + '\n';
  }
  p('## Projects');
  p();
  p('| Project | Stack | Package manager | Depends on |');
  p('| --- | --- | --- | --- |');
  for (const x of plan.projects) {
    const stack = [...x.frameworks.map((f) => `${f.name}${f.version ? ' ' + f.version : ''}`), ...x.ecosystems.filter((e) => e !== 'generic').map(label)].join(', ');
    p(`| \`${x.root}\` | ${stack || 'unrecognized'}${x.support === 'generic' ? ' (generic)' : ''} | ${x.packageManagers.map((m) => label(m.name)).join(', ') || '–'} | ${x.dependsOn.map((d) => `${projectLabel(plan, d.project)} (${d.kind})`).join(', ') || '–'} |`);
  }
  p();
  p('## Prerequisites');
  p();
  for (const r of plan.requirements.filter((x) => !x.optional)) p(`- ${requirementLine(r)} — ${conf(r.confidence)}; from ${r.evidence.slice(0, 2).map((e) => `\`${ref(e)}\``).join(', ') || 'the project type'}`);
  for (const s of plan.services.filter((x) => !x.optional)) p(`- ${serviceLine(s)} — ${conf(s.confidence)}`);
  const optional = [...plan.requirements.filter((r) => r.optional).map(requirementLine), ...plan.services.filter((s) => s.optional).map((s) => label(s.name))];
  if (optional.length) p(`- Optional: ${optional.join(', ')}`);
  p();
  p(`Run \`${plan.tool.name} doctor\` to check your machine against this list.`);
  p();
  if (plan.conflicts.length || plan.unknowns.length) {
    p('## Things to know');
    p();
    for (const x of plan.conflicts) p(`- ${x.severity === 'warning' ? '**Check:** ' : ''}${x.message}`);
    for (const u of plan.unknowns) p(`- **Unknown:** ${u.message}${u.suggestion ? ' ' + u.suggestion : ''}`);
    p();
  }
  p('## Steps');
  p();
  p('Run each command from the folder shown. Commands are given for macOS/Linux shells and for Windows PowerShell.');
  p();
  const block = (s: Step, i: number) => {
    p(`### ${i}. ${s.title}${s.optional ? ' (optional)' : ''}`);
    p();
    p(`${s.why}${s.network ? ' *Needs network access.*' : ''}${s.thirdPartyCode && s.action.type === 'exec' ? ' *Runs third-party code.*' : ''} Confidence: ${conf(s.confidence)}.`);
    p();
    if (s.action.type === 'manual') p(`> ${s.action.text}`);
    else {
      p('```bash');
      if (s.cwd !== '.') p(renderCd(s.cwd, 'posix'));
      p(renderAction(s.action, 'posix'));
      p('```');
      p();
      p('```powershell');
      if (s.cwd !== '.') p(renderCd(s.cwd, 'powershell'));
      p(renderAction(s.action, 'powershell'));
      p('```');
    }
    for (const n of s.notes) p(`- ${n}`);
    p();
  };
  plan.steps.filter((s) => !s.optional).forEach((s, i) => block(s, i + 1));
  const opt = plan.steps.filter((s) => s.optional);
  opt.forEach((s, i) => block(s, plan.steps.length - opt.length + i + 1));
  if (plan.run.length) {
    p('## Running');
    p();
    p('| Target | Directory | Command | Port |');
    p('| --- | --- | --- | --- |');
    for (const r of plan.run.filter((x) => x.primary || x.kind === 'production')) {
      p(`| ${r.kind} | \`${r.cwd}\` | \`${renderAction(r.action, 'posix')}\` | ${r.ports.map((x) => x.port).join(', ') || '–'} |`);
    }
    p();
  }
  const env = plan.env.filter((e) => e.vars.some((v) => v.fill === 'user' || v.fill === 'unknown'));
  if (env.length) {
    p('## Environment variables to fill in');
    p();
    for (const e of env) {
      p(`\`${e.file}\`${e.template ? ` (from \`${e.template}\`)` : ''}:`);
      p();
      for (const v of e.vars.filter((x) => x.fill === 'user' || x.fill === 'unknown')) p(`- \`${v.name}\`${v.secret ? ' (secret)' : ''}${v.fill === 'unknown' ? ' — read by the code, not in the template' : ''}${v.note ? ` — ${v.note}` : ''}`);
      p();
    }
  }
  return o.join('\n') + '\n';
}

function conf(c: string): string {
  return c === 'high' ? 'sure' : c === 'medium' ? '*likely*' : '*guess*';
}
